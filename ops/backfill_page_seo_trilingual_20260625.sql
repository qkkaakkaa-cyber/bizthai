DECLARE
    bad_count INT;
BEGIN
    SELECT COUNT(*) INTO bad_count
    FROM tmp_page_seo_i18n
    WHERE length(seo_title) > 255
       OR length(seo_keywords) > 512
       OR length(seo_description) > 512
       OR length(page_title) > 255;
    IF bad_count > 0 THEN
        RAISE EXCEPTION 'SEO backfill contains % over-length rows', bad_count;
    END IF;
END $$;

INSERT INTO cms_page_seo (site_id, page_id, seo_title, seo_keywords, seo_description, created_at, updated_at)
SELECT
    p.site_id,
    p.id,
    d.seo_title,
    d.seo_keywords,
    d.seo_description,
    now(),
    now()
FROM cms_pages p
JOIN tmp_page_seo_i18n d ON d.page_id = p.id AND d.locale = 'th'
WHERE p.site_id = 1
ON CONFLICT (site_id, page_id) DO UPDATE SET
    seo_title = EXCLUDED.seo_title,
    seo_keywords = EXCLUDED.seo_keywords,
    seo_description = EXCLUDED.seo_description,
    updated_at = now();

INSERT INTO cms_page_translations (
    page_id,
    site_id,
    locale,
    title,
    slug,
    summary,
    body,
    body_blocks,
    translation_status,
    seo_title,
    seo_keywords,
    seo_description,
    meta_json,
    source_hash,
    segment_hashes,
    created_at,
    updated_at
)
SELECT
    p.id,
    p.site_id,
    d.locale,
    d.page_title,
    p.slug,
    d.page_summary,
    COALESCE(p.body, ''),
    p.body_blocks,
    CASE WHEN p.status = 'published' THEN 'published' ELSE 'draft' END,
    d.seo_title,
    d.seo_keywords,
    d.seo_description,
    COALESCE(p.meta_json, '{}'::jsonb),
    '',
    NULL,
    now(),
    now()
FROM cms_pages p
JOIN tmp_page_seo_i18n d ON d.page_id = p.id
WHERE p.site_id = 1
ON CONFLICT (page_id, locale) DO UPDATE SET
    title = EXCLUDED.title,
    slug = EXCLUDED.slug,
    summary = EXCLUDED.summary,
    seo_title = EXCLUDED.seo_title,
    seo_keywords = EXCLUDED.seo_keywords,
    seo_description = EXCLUDED.seo_description,
    translation_status = EXCLUDED.translation_status,
    updated_at = now();

