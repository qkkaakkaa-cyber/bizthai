// 仅保留 markdown 输出会用到的标签;剔除脚本/样式/事件/文档级标签,杜绝服务端渲染注入
function sanitize(html) {
  return String(html || '')
    .replace(/<!\s*doctype[^>]*>/gi, '')
    .replace(/<\/?(?:script|style|iframe|object|embed|link|meta|html|head|body|base|form|input|button|svg|canvas|video|audio|source)\b[^>]*>/gi, '')
    .replace(/\son\w+\s*=\s*("[^"]*"|'[^']*'|[^\s>]+)/gi, '')
    .replace(/(href|src)\s*=\s*(["']?)\s*javascript:[^"'>\s]*\2/gi, '$1="#"')
}
