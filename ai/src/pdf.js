// 主入口:返回 PDF Buffer
export async function renderReportPdf({ title, bodyHtml, company = {}, lang = 'en' }) {
  lang = (T[lang] ? lang : 'en')
  // 末页二维码(基于公司在线档案 URL)
  if (company.url) {
    try { company._qr = await QRCode.toDataURL(String(company.url), { margin: 0, width: 240, errorCorrectionLevel: 'M' }) } catch { /* 无二维码也继续 */ }
  }
  const html = buildHtml({ title, bodyHtml, company, lang })
  const { header, footer } = headerFooter({ title, company, lang })

  const browser = await getBrowser()
  const page = await browser.newPage()
  try {
    await page.setJavaScriptEnabled(false)
    await page.setRequestInterception(true)
    page.on('request', r => {
      const u = r.url()
      if (u.startsWith('data:') || u.startsWith('about:') || u.startsWith('blob:')) r.continue()
      else r.abort()   // 阻断一切外部网络
    })
    await page.setContent(html, { waitUntil: 'load', timeout: 15000 })
    const pdf = await page.pdf({
      format: 'A4',
      printBackground: true,
      displayHeaderFooter: true,
      headerTemplate: header,
      footerTemplate: footer,
      margin: { top: '20mm', bottom: '16mm', left: '11mm', right: '11mm' },
    })
    return pdf
  } finally {
    await page.close().catch(() => {})
  }
}
